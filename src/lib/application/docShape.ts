/**
 * A drafted resume or letter is the document itself, nothing around it (#106). Held in code, not only
 * asked of the model: product artifacts come out, section names are the ones recruiters and ATS
 * expect, and a cover letter is a letter (greeting, paragraphs, close), not a list.
 */

/** Lines a model writes around a document, never in one: chat preambles, sign-offs to the user, reviewer notes, version labels. */
const ARTIFACT = [
  /^(sure|certainly|of course|absolutely|okay|ok)\b[,!.]/i,
  /^here('s| is| are)\b.*\b(resume|résumé|cv|cover letter|letter|draft|version)\b/i,
  /^(below|above) (is|are)\b.*\b(resume|résumé|cv|cover letter|letter|draft|version)\b/i,
  /^i('ve| have)\s+(tailored|updated|revised|rewritten|rewrote|drafted|written|made|kept|added|removed|adjusted)\b/i,
  /^(let me know|feel free|i hope this|hope this helps|would you like)\b/i,
  /^\(?\[?\s*(note|notes|reviewer|reviewer notes?|editor'?s? notes?|todo|tbd|placeholder)\s*[:\]-]/i,
  /^(draft|version)\s*\d+(\.\d+)?\b/i,
  /^v\d+(\.\d+)?\s*[:–-]?\s*$/i,
  /^(tailored|customi[sz]ed|optimi[sz]ed|generated|written|drafted|prepared) (for|by)\b/i,
  /\b(as an ai|ai[- ]generated|generated by (ai|lookout|claude|chatgpt|gpt)|language model)\b/i,
  /^```/,
  /^<!--.*-->$/,
  /^(-{3,}|\*{3,}|_{3,})$/,
];

/** Inline leftovers: HTML comments, [bracketed placeholders], "(v3)" labels. */
const INLINE: [RegExp, string][] = [
  [/<!--[\s\S]*?-->/g, ""],
  [/\[(insert|add|your|placeholder|tbd|todo|note)[^\]]*\]/gi, ""],
  [/\s*\((v|version |draft )\d+(\.\d+)?\)/gi, ""],
];

/** Drop product artifacts from a drafted document. Returns the clean text and the lines it removed. */
export function scrubArtifacts(md: string): { md: string; removed: string[] } {
  const removed: string[] = [];
  const kept: string[] = [];
  for (const raw of md.replace(/\r/g, "").split("\n")) {
    const plain = raw.trim().replace(/^#{1,4}\s+/, "").replace(/^[-*•]\s+/, "").replace(/\*\*/g, "");
    if (plain && ARTIFACT.some((r) => r.test(plain))) {
      removed.push(raw.trim());
      continue;
    }
    let line = raw;
    for (const [r, s] of INLINE) line = line.replace(r, s);
    if (line.trim() !== raw.trim() && !line.trim()) {
      removed.push(raw.trim());
      continue;
    }
    kept.push(line.replace(/\s+$/, ""));
  }
  return { md: kept.join("\n").replace(/\n{3,}/g, "\n\n").trim(), removed };
}

/** The section names recruiters and parsers look for, from the many ways a draft words them. */
const CANON: [RegExp, string][] = [
  [/^(summary|profile|professional (summary|profile)|career (summary|profile)|executive summary|summary of qualifications|about( me)?|overview|objective)$/i, "Summary"],
  [/^((work|professional|relevant|employment|career) (experience|history)|experience|employment|work history)$/i, "Experience"],
  [/^((technical|core|key|relevant) (skills|competencies)|skills( (&|and) (tools|technologies|expertise))?|core competencies|competencies|areas of expertise|expertise|tools( (&|and) technologies)?)$/i, "Skills"],
  [/^(education( (&|and) training)?|academic background|academics)$/i, "Education"],
];

/** Rename resume sections to the standard names. Leaves other sections (Selected Projects, Certifications) as written. */
export function standardSections(md: string): { md: string; fixed: string[] } {
  const fixed: string[] = [];
  const out = md.split("\n").map((l) => {
    const m = l.match(/^##\s+(.*)$/);
    if (!m || /^###/.test(l)) return l;
    const was = m[1].replace(/\*/g, "").replace(/:$/, "").trim();
    const hit = CANON.find(([r]) => r.test(was));
    if (!hit || hit[1] === was) return l;
    fixed.push(`Named the "${was}" section "${hit[1]}", the name recruiters and ATS look for.`);
    return `## ${hit[1]}`;
  });
  return { md: out.join("\n"), fixed };
}

/** One way to write a date range on role lines: "MM/YYYY – MM/YYYY", en dash, dates last. */
export function roleDates(md: string) {
  return md
    .split("\n")
    .map((l) => (/^#{3,4}\s+/.test(l) ? l.replace(/(\d{4}|\b[A-Z][a-z]{2,8}\.? \d{4})\s*(?:-|–|to)\s*((?:\d{1,2}\/)?\d{4}|[A-Z][a-z]{2,8}\.? \d{4}|present|current)\s*$/i, "$1 – $2") : l))
    .join("\n");
}

/** Everything code holds a drafted resume to before anyone sees it. Returns what it changed. */
export function cleanResume(md: string): { md: string; fixed: string[] } {
  const s = scrubArtifacts(md);
  const n = standardSections(roleDates(s.md));
  return { md: n.md, fixed: [...(s.removed.length ? [`Removed text that wasn't part of the resume: ${s.removed.map((r) => `"${r.slice(0, 60)}"`).join(", ")}`] : []), ...n.fixed] };
}

const GREETING = /^(dear|hello|hi|to whom|greetings)\b.*[,:]?$/i;
const CLOSE = /^(sincerely|best|best regards|kind regards|regards|warm regards|warmly|thank you|thanks|respectfully|with thanks|all the best|cheers)[,.!]?$/i;

/** A letter fits one page under about this many words, with the header. */
export const LETTER_MAX_WORDS = 380;

/**
 * A cover letter that reads as one a person wrote: a greeting, paragraphs, a close and the name. No
 * headings, no markdown, and no bullet lists unless the person asked for them.
 */
export function shapeLetter(md: string, o: { name: string; company?: string; bullets?: boolean }): { md: string; fixed: string[] } {
  const fixed: string[] = [];
  const s = scrubArtifacts(md);
  if (s.removed.length) fixed.push(`Removed text that wasn't part of the letter: ${s.removed.map((r) => `"${r.slice(0, 60)}"`).join(", ")}`);
  let lines = s.md.split("\n").map((l) => l.trim());

  // No headings or bold in a letter. The name and contact header come from the resume, above the letter.
  if (lines.some((l) => /^#{1,4}\s+/.test(l))) {
    lines = lines.filter((l) => !/^#{1,4}\s+/.test(l));
    fixed.push("Took the headings out: a letter has none.");
  }
  lines = lines.map((l) => l.replace(/\*\*(.+?)\*\*/g, "$1").replace(/(^|[^*])\*(?!\s)(.+?)\*/g, "$1$2"));

  // Bullet runs become one paragraph of sentences.
  if (!o.bullets && lines.some((l) => /^[-*•]\s+/.test(l))) {
    const out: string[] = [];
    let run: string[] = [];
    const flush = () => {
      if (run.length) out.push(run.map((b) => (/[.!?]$/.test(b) ? b : `${b}.`)).join(" "));
      run = [];
    };
    for (const l of lines) {
      if (/^[-*•]\s+/.test(l)) {
        const b = l.replace(/^[-*•]\s+/, "").trim();
        run.push(b.charAt(0).toUpperCase() + b.slice(1));
      } else {
        flush();
        out.push(l);
      }
    }
    flush();
    lines = out;
    fixed.push("Wrote the bullet list as a paragraph: a cover letter reads as prose.");
  }

  let body = lines.join("\n").replace(/\n{3,}/g, "\n\n").trim().split("\n");
  const first = body.findIndex((l) => l);
  if (first < 0) return { md: "", fixed };
  if (!GREETING.test(body[first])) {
    body = [`Dear ${o.company ? `${o.company} ` : ""}Hiring Team,`, "", ...body.slice(first)];
    fixed.push("Added a greeting.");
  }
  const closeAt = body.findIndex((l) => CLOSE.test(l));
  if (closeAt < 0) {
    body = [...body, "", "Sincerely,", o.name.trim()].filter((l, i, a) => !(l === "" && a[i - 1] === ""));
    fixed.push("Added a sign-off.");
  } else if (!body.slice(closeAt + 1).some((l) => l.trim()) && o.name.trim()) body = [...body.slice(0, closeAt + 1), o.name.trim()];
  const out = body.join("\n").replace(/\n{3,}/g, "\n\n").trim();
  const words = out.split(/\s+/).filter(Boolean).length;
  if (words > LETTER_MAX_WORDS) fixed.push(`At ${words} words this runs past one page. Cut it to about 250.`);
  return { md: out, fixed };
}

/** Did the person ask for a list in their instruction? Then a letter may keep bullets. */
export const asksForBullets = (instruction: string) => /\b(bullet|bulleted|bullets|list|lists|point form)\b/i.test(instruction);
