import { describe, expect, it } from "vitest";
import { asksForBullets, cleanResume, scrubArtifacts, shapeLetter, standardSections } from "./docShape";
import { parseDraft } from "./resumeLayout";

// What a model sometimes hands back: chat around the resume, a version label, a reviewer note,
// and section names a parser won't know.
const raw = `Here is your tailored resume for the Staff Designer role:

# Maya Ortiz
Design Systems Lead
New York, NY • maya@example.com

## Professional Summary
Builds design systems that ship across a firm.

## Work Experience
<!-- reviewer: check dates -->
### Design Systems Lead, Acme | New York, NY | 07/2021 - Present
- Built the component library used by 40 teams.
- [Note: add a metric here]
### Front-End Developer, Studio | 2016 to 2021
- Shipped fast marketing sites.

## Core Competencies
React, TypeScript, Figma

## Education
BFA, Parsons

---
Version 3 (tailored for Acme)
Let me know if you'd like any changes!`;

describe("cleanResume", () => {
  const { md, fixed } = cleanResume(raw);

  it("keeps only the resume: no preamble, notes, version labels or AI mentions", () => {
    for (const bad of ["Here is", "reviewer", "[Note", "Version 3", "Let me know", "---", "<!--"]) expect(md).not.toContain(bad);
    expect(md.startsWith("# Maya Ortiz")).toBe(true);
    expect(fixed.join(" ")).toContain("wasn't part of the resume");
  });

  it("uses the standard section names, in the draft's order", () => {
    expect(parseDraft(md).filter((b) => b.t === "section").map((b) => b.text)).toEqual(["Summary", "Experience", "Skills", "Education"]);
  });

  it("writes every date range the same way", () => {
    const roles = parseDraft(md).filter((b) => b.t === "role");
    expect(roles.map((r) => r.right)).toEqual(["07/2021 – Present", "2016 – 2021"]);
  });

  it("keeps the content itself", () => {
    expect(md).toContain("- Built the component library used by 40 teams.");
    expect(md).toContain("New York, NY • maya@example.com");
  });
});

describe("scrubArtifacts", () => {
  it("leaves real bullets that only look close", () => {
    const md = "- Version-controlled the design tokens.\n- Drafted the hiring plan for 3 roles.\n- Tuned the V8 build for 2x faster loads.";
    expect(scrubArtifacts(md)).toEqual({ md, removed: [] });
  });

  it("catches AI references anywhere in a line", () => {
    expect(scrubArtifacts("Body text.\nThis letter was AI-generated by Lookout.").md).toBe("Body text.");
  });
});

describe("standardSections", () => {
  it("leaves sections it has no standard name for", () => {
    expect(standardSections("## Selected Projects\n## Certifications").md).toBe("## Selected Projects\n## Certifications");
  });
});

describe("shapeLetter", () => {
  it("makes a list into a letter: greeting, prose, sign-off with the name", () => {
    const { md, fixed } = shapeLetter("Sure! Here's your cover letter:\n\n## Why me\n- built the design system\n- led five engineers\n\nI'd start with the token audit.", { name: "Maya Ortiz", company: "Acme" });
    expect(md).toBe("Dear Acme Hiring Team,\n\nBuilt the design system. Led five engineers.\n\nI'd start with the token audit.\n\nSincerely,\nMaya Ortiz");
    expect(md).not.toMatch(/^[-*•#]/m);
    expect(fixed.length).toBeGreaterThanOrEqual(3);
  });

  it("leaves a letter that already reads as one alone", () => {
    const letter = "Dear Ms. Lee,\n\nI lead design systems at Acme.\n\nBest regards,\nMaya Ortiz";
    expect(shapeLetter(letter, { name: "Maya Ortiz" })).toEqual({ md: letter, fixed: [] });
  });

  it("adds the name under a close that has none", () => {
    expect(shapeLetter("Dear team,\n\nBody.\n\nSincerely,", { name: "Maya Ortiz" }).md).toBe("Dear team,\n\nBody.\n\nSincerely,\nMaya Ortiz");
  });

  it("keeps bullets when the person asked for them", () => {
    expect(asksForBullets("Make the middle a bulleted list")).toBe(true);
    expect(shapeLetter("Dear team,\n\n- one\n- two\n\nSincerely,\nMaya", { name: "Maya", bullets: true }).md).toContain("- one\n- two");
  });

  it("flags a letter too long for one page", () => {
    const long = `Dear team,\n\n${"word ".repeat(400)}\n\nSincerely,\nMaya`;
    expect(shapeLetter(long, { name: "Maya" }).fixed.join(" ")).toContain("past one page");
  });
});
